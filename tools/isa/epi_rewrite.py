#!/usr/bin/env python3
"""ISA-level rewrite of the per-token dequantisation epilogue of w4np_r (Xe2 text from isa_patch -d, SWSB stripped).
Per (token, 64-K group) the compiler emitted   A: Y = as*ws   B: X = zw*(as*sm)   C: (1-lane) S = as*sm   D: X = f*Y - X   E: acc += X      (4 vector + 1 scalar instruction)
Rewritten to   B': X = zw*sm   D': X = f*ws - X   E': acc = acc + X*as                                                                        (3 vector instructions)
i.e. acc += as*(f*ws - zw*sm).  Dependencies are checked textually; SWSB is regenerated by IGA (isa_patch -a)."""
import re, sys
L = open(sys.argv[1]).read().split('\n')
RA = re.compile(r'^\s*mul \(16\|M0\)\s+(acc\d)\.0<1>:f\s+(r\d+\.\d+)<0;1,0>:f\s+(r\d+\.0)<1;1,0>:f\s*$')
RB = re.compile(r'^\s*mul \(16\|M0\)\s+(acc\d)\.0<1>:f\s+(acc\d)\.0<1;1,0>:f\s+(r\d+\.\d+)<0;1,0>:f\s*$')
RC = re.compile(r'^\s*mul \(1\|M0\)\s+(r\d+\.\d+)<1>:f\s+(r\d+\.\d+)<0;1,0>:f\s+(r\d+\.\d+)<0;1,0>:f\s*$')
RD = re.compile(r'^\s*mad \(16\|M0\)\s+(acc\d)\.0<1>:f\s+-(acc\d)\.0<1;0>:f\s+(acc\d)\.0<1;0>:f\s+(r\d+\.0)<1>:f\s*$')
RE = re.compile(r'^\s*add \(16\|M0\)\s+(r\d+)\.0<1>:f\s+(r\d+)\.0<1;1,0>:f\s+(acc\d)\.0<1;1,0>:f\s*$')
TB = {'f': 4, 'd': 4, 'ud': 4, 'hf': 2, 'w': 2, 'uw': 2, 'b': 1, 'ub': 1, 'q': 8, 'uq': 8, 'df': 8}
def written(l):
    """set of GRF numbers written by the instruction text l (None if unknown -> treated as writing nothing)"""
    m = re.match(r'^\s*(?:\([^)]*\)\s*)?(send\S*)\s+\((\d+)\|M\d+\)\s+(?:null|r(\d+))\s', l)
    if m:
        if m.group(3) is None: return set()
        mm = re.search(r'rd:(\d+)', l); n = int(mm.group(1)) if mm else 1
        return set(range(int(m.group(3)), int(m.group(3)) + n))
    m = re.match(r'^\s*(?:\([^)]*\)\s*)?(dpas\S*)\s+\((\d+)\|M\d+\)\s+r(\d+):d', l)
    if m: return set(range(int(m.group(3)), int(m.group(3)) + 8))
    m = re.match(r'^\s*(?:\([^)]*\)\s*)?[a-z0-9.]+\s+\((\d+)\|M\d+\)\s+r(\d+)\.(\d+)<(\d+)>:(\w+)', l)
    if m:
        ex, r, sub, st, ty = int(m.group(1)), int(m.group(2)), int(m.group(3)), int(m.group(4)), m.group(5)
        by = TB.get(ty, 4); last = sub * by + (ex - 1) * st * by + by - 1
        return set(range(r, r + last // 64 + 1))
    return set()
def grf_of(opnd): return int(re.match(r'r(\d+)', opnd).group(1))
def writes(lines, lo, hi, grf):
    return any(grf in written(L[i]) for i in range(lo, hi))
import os
LO = int(os.environ.get('BLK_LO', 0)); HI = int(os.environ.get('BLK_HI', 10**9)); ordn = -1
dele = set(); rep = {}; nblk = 0; skipped = 0
for d, l in enumerate(L):
    m = RD.match(l)
    if not m: continue
    D0, X, Y, F = m.groups()
    ia = ib = None
    for i in range(d - 1, max(d - 400, 0), -1):
        a = RA.match(L[i])
        if a and a.group(1) == Y: ia = i; break
        if re.match(r'^\s*\S+ \(\d+\|M0\)\s+' + Y + r'\.', L[i]): break
    for i in range(d - 1, max(d - 400, 0), -1):
        b = RB.match(L[i])
        if b and b.group(1) == X: ib = i; break
        if re.match(r'^\s*\S+ \(\d+\|M0\)\s+' + X + r'\.', L[i]): break
    if ia is None or ib is None: skipped += 1; continue
    a = RA.match(L[ia]); b = RB.match(L[ib]); _, asr, ws = a.groups(); _, zw, S = b.groups()
    ic = None
    for i in range(ib - 1, max(ib - 400, 0), -1):
        c = RC.match(L[i])
        if c and c.group(1) == S: ic = i; break
        if grf_of(S) in written(L[i]) and not RC.match(L[i]): break
    ie = None
    for i in range(d + 1, min(d + 30, len(L))):
        e = RE.match(L[i])
        if e and e.group(3) == D0: ie = i; break
    if ic is None or ie is None: skipped += 1; continue
    c = RC.match(L[ic]); _, asc, sm = c.groups(); T = RE.match(L[ie]).group(1)
    if asc != asr: skipped += 1; continue
    # sm must be unchanged between C and B, as must stay valid up to E, ws up to D, zw up to B
    if writes(L, ic + 1, ib, grf_of(sm)) or writes(L, ic + 1, ie, grf_of(asr)) or writes(L, ia + 1, d, grf_of(ws)): skipped += 1; continue
    if ic in dele or ia in dele: skipped += 1; continue
    ordn += 1
    if not (LO <= ordn < HI): continue
    rep[ib] = f'        mul (16|M0)              {X}.0<1>:f   {zw}.0<1;1,0>:f   {sm}<0;1,0>:f'
    rep[d] = f'        mad (16|M0)              {D0}.0<1>:f   -{X}.0<1;0>:f    {ws}<1;0>:f     {F}<1>:f'
    rep[ie] = f'        mad (16|M0)              {T}.0<1>:f   {T}.0<1;0>:f   {D0}.0<1;0>:f   {asr}<0>:f'
    dele.add(ia); dele.add(ic); nblk += 1
out = [rep.get(i, l) for i, l in enumerate(L) if i not in dele]
open(sys.argv[2], 'w').write('\n'.join(out))
print(f'rewritten blocks {nblk}, skipped {skipped}, instructions removed {len(dele)}', file=sys.stderr)
